// Орфография: архивные документы пишутся в дореформенной орфографии, кнопка «В современной орфографии»
// переводит их обратно. Протокол игрока показывается превью «как в 1913 году» — приближённо.

const VOWELS = 'аеёиоуыэюяіѣ';

/** Дореформенная → современная (детерминированно и почти без исключений). */
export function oldToModern(text: string): string {
  let s = text
    .replace(/ѣ/g, 'е').replace(/Ѣ/g, 'Е')
    .replace(/[іi](?=[аеёиоуыэюяйАЕЁИОУЫЭЮЯЙ])/g, 'и')
    .replace(/і/g, 'и').replace(/І/g, 'И')
    .replace(/ѳ/g, 'ф').replace(/Ѳ/g, 'Ф')
    .replace(/ѵ/g, 'и').replace(/Ѵ/g, 'И');
  // твёрдый знак на конце слова
  s = s.replace(/([бвгджзклмнпрстфхцчшщБВГДЖЗКЛМНПРСТФХЦЧШЩ])[ъЪ](?=$|[^а-яёА-ЯЁ])/g, '$1');
  // окончания прилагательных -аго/-яго → -ого/-его
  s = s.replace(/([а-яё]{2,})аго(?=$|[^а-яё])/g, '$1ого').replace(/([а-яё]{2,})яго(?=$|[^а-яё])/g, '$1его');
  // -ыя/-ія во множественном числе прилагательных
  s = s.replace(/([а-яё]{2,})ыя(?=$|[^а-яё])/g, '$1ые').replace(/([а-яё]{2,})ія(?=$|[^а-яё])/g, '$1ие');
  return s;
}

// Частые корни с «ять» — для превью протокола. Не исчерпывающе: это стилизация, а не транслитератор.
const YAT_ROOTS = [
  'слѣдоват', 'слѣд', 'дѣйств', 'сдѣла', 'дѣл', 'мѣст', 'свѣт', 'мѣр', 'провѣр', 'увѣр', 'довѣр', 'вѣрн', 'бѣл',
  'сѣры', 'сѣра', 'сѣро', 'цѣнн', 'цѣна', 'цѣну', 'лѣв', 'желѣз', 'рѣка', 'рѣки', 'обрѣз', 'вѣтх', 'тѣло', 'тѣла',
  'отвѣт', 'совѣт', 'бесѣд', 'свидѣтел', 'видѣл', 'сидѣл', 'смотрѣ', 'имѣе', 'имѣл', 'имѣю', 'умѣе', 'умѣл', 'хотѣ',
  'нѣск', 'нѣкот', 'лѣстн', 'стѣн', 'сѣно', 'сѣна', 'сѣвер', 'обѣд', 'хлѣб', 'мѣшок', 'мѣшк', 'полѣн', 'колѣн', 'рѣдк',
  'цѣл', 'бѣд', 'вѣк', 'пѣсн', 'снѣг', 'тѣн', 'измѣр', 'примѣт', 'замѣт', 'помѣт', 'помѣщ', 'помѣст', 'вмѣст', 'ѣхал',
  'ѣзд', 'вѣдом', 'увѣдом', 'дѣтск', 'клѣт', 'тѣсн', 'утѣш', 'цвѣт', 'пѣн', 'рѣш', 'грѣх', 'спѣш', 'успѣ', 'смѣн', 'смѣс',
];
const YAT_WORDS: Record<string, string> = { где: 'гдѣ', здесь: 'здѣсь', нет: 'нѣтъ', две: 'двѣ', вне: 'внѣ', после: 'послѣ', везде: 'вездѣ' };
const YAT_PAIRS = YAT_ROOTS.map((r) => [r.replace(/ѣ/g, 'е'), r] as const).sort((a, b) => b[0].length - a[0].length);
const KEEP_OGO = new Set(['того', 'кого', 'чего', 'всего', 'него', 'ничего', 'никого', 'сего', 'своего', 'моего', 'его', 'много', 'немного', 'строго', 'долго', 'одного']);

function convertWord(w: string): string {
  if (!/^[а-яё]+$/i.test(w)) return w;
  const lower = w.toLowerCase();
  if (YAT_WORDS[lower]) return w[0] !== w[0].toLowerCase() ? YAT_WORDS[lower][0].toUpperCase() + YAT_WORDS[lower].slice(1) : YAT_WORDS[lower];
  let o = lower;
  for (const [mod, old] of YAT_PAIRS) {
    if (o.startsWith(mod) || o.includes(mod)) {
      o = o.replace(mod, old);
      break;
    }
  }
  if (!KEEP_OGO.has(lower)) {
    if (/[жшчщ]его$/.test(o) && o.length > 5) o = o.replace(/его$/, 'аго');
    else if (/[^жшчщ]ого$/.test(o) && o.length > 5) o = o.replace(/ого$/, 'аго');
    else if (/него$/.test(o) && o.length > 6) o = o.replace(/него$/, 'няго');
  }
  o = o.replace(/и(?=[аеёиоуыэюяй])/g, 'і');
  if (/[бвгджзклмнпрстфхцчшщ]$/.test(o)) o += 'ъ';
  // восстановить регистр первой буквы
  if (w[0] !== w[0].toLowerCase()) o = o[0].toUpperCase() + o.slice(1);
  if (w === w.toUpperCase() && w.length > 1) o = o.toUpperCase();
  return o;
}

/** Современная → «как в 1913 году» (превью, приближённо). */
export function modernToOld(text: string): string {
  return text.replace(/[а-яё]+/gi, (w) => convertWord(w));
}

export function isVowel(ch: string) {
  return VOWELS.includes(ch.toLowerCase());
}
